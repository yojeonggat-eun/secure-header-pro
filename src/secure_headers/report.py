from datetime import datetime
from html import escape
import os
import re

def sanitize_filename(url: str) -> str:
    """Clean the URL so it can be used in a filename."""
    name = re.sub(r'https?://', '', url)
    name = re.sub(r'^www\.', '', name)
    name = name.replace('/', '_').replace(':', '_')
    name = re.sub(r'[^\w\-.]', '_', name)
    return name[:50]

def generate_html_report(url: str, analysis: dict, score_data: dict, final_url: str, nginx_config: str, apache_config: str) -> str:
    """
    Generate a complete HTML report with analysis + fix configs.
    """
    grade = score_data["grade"]
    score = score_data["score"]

    # Header values come from the scanned site, so they are untrusted:
    # escape them before putting them into HTML (prevents HTML/script injection).
    safe_url = escape(url)
    safe_final_url = escape(final_url)
    safe_nginx = escape(nginx_config)
    safe_apache = escape(apache_config)

    if grade in ["A+", "A"]:
        grade_color = "#28a745"
    elif grade in ["B", "C"]:
        grade_color = "#ffc107"
    else:
        grade_color = "#dc3545"

    # Build analysis rows
    rows = ""
    for key, data in analysis.items():
        status = data["status"]
        if status in ["Good", "Present"]:
            status_color = "#28a745"
        elif status == "Weak":
            status_color = "#ffc107"
        else:
            status_color = "#dc3545"

        rows += f"""
        <tr>
            <td>{escape(key.replace('_', '-').title())}</td>
            <td style="color: {status_color}; font-weight: bold;">{escape(status)}</td>
            <td>{escape(data['message'])}</td>
        </tr>
        """

    html = f"""
<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <title>Security Headers Report - {safe_url}</title>
    <style>
        body {{
            font-family: Arial, sans-serif;
            max-width: 950px;
            margin: 40px auto;
            padding: 20px;
            background-color: #f8f9fa;
            color: #333;
            line-height: 1.6;
        }}
        .header {{
            text-align: center;
            margin-bottom: 30px;
        }}
        .grade-box {{
            display: inline-block;
            padding: 15px 30px;
            border-radius: 8px;
            background-color: {grade_color};
            color: white;
            font-size: 24px;
            font-weight: bold;
            margin: 15px 0;
        }}
        table {{
            width: 100%;
            border-collapse: collapse;
            margin-top: 20px;
            background: white;
        }}
        th, td {{
            padding: 12px;
            border: 1px solid #ddd;
            text-align: left;
        }}
        th {{
            background-color: #343a40;
            color: white;
        }}
        pre {{
            background-color: #1e1e1e;
            color: #d4d4d4;
            padding: 18px;
            border-radius: 6px;
            overflow-x: auto;
            font-size: 14px;
            line-height: 1.5;
        }}
        .section {{
            margin-top: 40px;
        }}
        .footer {{
            margin-top: 50px;
            font-size: 14px;
            color: #666;
            text-align: center;
        }}
        h2 {{
            border-bottom: 2px solid #ddd;
            padding-bottom: 8px;
        }}
    </style>
</head>
<body>
    <div class="header">
        <h1>Security Headers Report</h1>
        <p><strong>Target:</strong> {safe_url}</p>
        <p><strong>Final URL:</strong> {safe_final_url}</p>
        <div class="grade-box">Grade: {grade} &nbsp;|&nbsp; Score: {score}/100</div>
    </div>

    <div class="section">
        <h2>Detailed Analysis</h2>
        <table>
            <thead>
                <tr>
                    <th>Header</th>
                    <th>Status</th>
                    <th>Details</th>
                </tr>
            </thead>
            <tbody>
                {rows}
            </tbody>
        </table>
    </div>

    <div class="section">
        <h2>How to Fix (Nginx)</h2>
        <p>Copy and paste the following configuration inside your Nginx <code>server {{ }}</code> block:</p>
        <pre>{safe_nginx}</pre>
    </div>

    <div class="section">
        <h2>How to Fix (Apache)</h2>
        <p>Copy and paste the following configuration in your <code>.htaccess</code> file or VirtualHost:</p>
        <pre>{safe_apache}</pre>
    </div>

    <div class="footer">
        Report generated by <strong>SecureHeaderPro</strong> on {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}
    </div>
</body>
</html>
"""
    return html

def save_reports(url: str, analysis: dict, score_data: dict, final_url: str, nginx_config: str, apache_config: str):
    """
    Save both HTML and TXT reports in a reports/ folder.
    """
    os.makedirs("reports", exist_ok=True)

    timestamp = datetime.now().strftime("%Y-%m-%d_%H-%M-%S")
    clean_name = sanitize_filename(url)
    base_name = f"{clean_name}_{timestamp}"

    html_path = f"reports/report_{base_name}.html"
    txt_path = f"reports/scan_{base_name}.txt"

    # Save HTML report (now includes configs)
    html_content = generate_html_report(url, analysis, score_data, final_url, nginx_config, apache_config)
    with open(html_path, "w", encoding="utf-8") as f:
        f.write(html_content)

    # Save TXT summary
    grade = score_data["grade"]
    score = score_data["score"]

    txt_content = f"""SecureHeaderPro - Scan Report
================================
Target      : {url}
Final URL   : {final_url}
Date        : {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}
Grade       : {grade}
Score       : {score}/100

Detailed Analysis
-----------------
"""
    for key, data in analysis.items():
        txt_content += f"{key.replace('_', '-').title():<25} | {data['status']:<10} | {data['message']}\n"

    txt_content += f"""
Nginx Configuration
-------------------
{nginx_config}

Apache Configuration
--------------------
{apache_config}
"""

    with open(txt_path, "w", encoding="utf-8") as f:
        f.write(txt_content)

    return html_path, txt_path